// ---------- размеры PNG ----------
function pngSize(file) {
  const b = fs.readFileSync(file);
  return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
}
// вписать картинку в прямоугольник с сохранением пропорций
function fit(file, box) {
  const { w, h } = pngSize(file);
  const s = Math.min(box.w / w, box.h / h);
  const iw = w * s, ih = h * s;
  return { path: file, x: box.x + (box.w - iw) / 2, y: box.y + (box.h - ih) / 2, w: iw, h: ih };
}
function addImg(s, file, box, caption) {
  const capH = caption ? 0.3 : 0;
  const f = fit(file, { ...box, h: box.h - capH });
  s.addImage(f);
  if (caption) {
    s.addText(caption, { x: box.x, y: f.y + f.h + 0.04, w: box.w, h: 0.26, fontFace: FONT, fontSize: 11, color: MUTED, align: 'center', margin: 0, isTextBox: true });
  }
}
function body(s, text, box, opts = {}) {
  s.addText(text, {
    x: box.x, y: box.y, w: box.w, h: box.h, fontFace: opts.mono ? MONO : FONT,
    fontSize: opts.fontSize || 13, color: INK, margin: 0, valign: opts.valign || 'top',
    lineSpacingMultiple: opts.lsm || 1.12, isTextBox: true, ...(opts.extra || {}),
  });
}
// маркированный список с форматированием внутри пункта:
// каждый пункт — массив фрагментов [{ text, options }, ...]
function richBullets(items, gap = 8) {
  const out = [];
  for (const runs of items) {
    runs.forEach((r, i) => {
      out.push({
        text: r.text,
        options: {
          ...(r.options || {}),
          ...(i === 0 ? { bullet: { code: '2022' }, indentLevel: 0 } : {}),
          ...(i === runs.length - 1 ? { breakLine: true, paraSpaceAfter: gap } : {}),
        },
      });
    });
  }
  return out;
}
function bullets(items, opts = {}) {
  return items.map((t) => (typeof t === 'string'
    ? { text: t, options: { bullet: { code: '2022' }, indentLevel: 0, paraSpaceAfter: opts.gap ?? 5 } }
    : t));
}
// моноширинная таблица (DDT и т. п.)
function monoBlock(s, lines, box, fontSize) {
  s.addText(lines.join('\n'), {
    x: box.x, y: box.y, w: box.w, h: box.h, fontFace: MONO, fontSize,
    color: INK, margin: 0, valign: 'top', lineSpacingMultiple: 1.0, isTextBox: true,
  });
}

